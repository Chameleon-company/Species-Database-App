"""Generate the production SQL that loads the reviewed Tetum translation sheet.

Reads the workbook, derives the Tetum leaf/fruit type from the English type with
the owner-approved terms, and writes one transactional script plus its rollback.
"""
from pathlib import Path

import openpyxl

HERE = Path(__file__).resolve().parent
SHEET = HERE / "tetum-translation-2026-11-27.xlsx"
OUT = HERE
STAMP = "20261127"

COLS = ["sr", "scientific_name", "etymology", "common_name", "habitat", "phenology",
        "identification_character", "leaf_type", "fruit_type", "seed_germination", "pest"]
TEXT_COLS = ["common_name", "etymology", "habitat", "identification_character", "leaf_type",
             "fruit_type", "phenology", "seed_germination", "pest"]

# Owner decisions (2026-11-27): one Tetum term per type, the sheet's majority wording;
# Sterculia foetida (palmately compound) is "Kompostu palmatu".
LEAF = {
    "simple": "Simples",
    "pinnately compound (single)": "Kompostu pinnadu (ida de'it)",
    "pinnately compound (double)": "Kompostu pinnadu (Duplu)",
    "palmately compound": "Kompostu palmatu",
}
FRUIT = {
    "drupe": "Drupe /ai-fuan ne'ebe iha parte toos ida ne'ebe proteje ninia musan",
    "capsule": "Kapsul",
    "follicle": "Fuan follicle (fuan ida naruk ne\u2019eb\u00e9 nakloke husi laran ida hodi f\u00f3 musan barak)",
    "pod": "Pod (fuan naruk ne\u2019eb\u00e9 iha musan iha laran)",
}


def read(ws):
    rows = []
    for r in ws.iter_rows(min_row=2, values_only=True):
        if not any(c not in (None, "") for c in r[:11]):
            continue
        rows.append({k: ("" if v is None else str(v).strip()) for k, v in zip(COLS, r[:11])})
    return rows


wb = openpyxl.load_workbook(SHEET, data_only=True)
en, tet = read(wb["species"]), read(wb["Tetum Version"])
assert len(en) == len(tet) == 22, (len(en), len(tet))

records, changed_terms = [], []
for e, t in zip(en, tet):
    assert e["scientific_name"] == t["scientific_name"], (e["scientific_name"], t["scientific_name"])
    rec = {c: t[c] for c in TEXT_COLS}
    leaf = LEAF[e["leaf_type"].lower()]
    fruit = FRUIT[e["fruit_type"].lower()]
    if rec["leaf_type"] != leaf:
        changed_terms.append((e["scientific_name"], "leaf_type", rec["leaf_type"], leaf))
    if rec["fruit_type"] != fruit:
        changed_terms.append((e["scientific_name"], "fruit_type", rec["fruit_type"], fruit))
    rec["leaf_type"], rec["fruit_type"] = leaf, fruit
    for c in TEXT_COLS:
        assert rec[c], (e["scientific_name"], c, "empty")
        assert "$tet$" not in rec[c]
    records.append((e["scientific_name"], rec))


def q(s):
    return "$tet$" + s + "$tet$"


values = ",\n".join(
    "    (" + ", ".join([q(name)] + [q(rec[c]) for c in TEXT_COLS]) + ")" for name, rec in records
)

sql = f"""-- =============================================================================
-- Load the reviewed Tetum translation into production (species_tet)
-- =============================================================================
-- Source: tetum-translation-2026-11-27.xlsx, sheet "Tetum Version" (22 species),
-- the reviewed translation received 2026-11-27. Generated by gen_sql.py; do not hand-edit.
--
-- What it does, in one transaction:
--   1. Checks every scientific name in the sheet matches exactly one species_en row.
--   2. Copies species_tet as it is now into public.species_tet_backup_{STAMP}
--      (only on the first run, so a re-run keeps the original copy).
--   3. Replaces the Tetum text of the 22 species with the sheet's text. Leaf and
--      fruit type use one agreed Tetum term per type (owner decision 2026-11-27).
--   4. Deletes Tetum rows that have no English row (the 5 duplicates, ids 23-27
--      on 2026-11-26), which the sheet supersedes.
--   5. Logs UPDATE / DELETE rows in changelog so installed apps re-sync. More than
--      20 species change, so devices download the full bundle once.
--   6. Checks that every English species has exactly one Tetum row and that no
--      Tetum row lacks an English row. Any failed check rolls everything back.
--
-- English text (species_en) is not changed: the sheet's English matches production.
-- Rollback: rollback-01-load-tetum-translation-{STAMP}.sql
-- Run in the Supabase SQL editor of project oppcngtkhywxsazeqqet.
-- =============================================================================

BEGIN;

CREATE TEMP TABLE tet_sheet (
    scientific_name text PRIMARY KEY,
    {", ".join(c + " text NOT NULL" for c in TEXT_COLS)}
) ON COMMIT DROP;

INSERT INTO tet_sheet (scientific_name, {", ".join(TEXT_COLS)}) VALUES
{values};

DO $$
DECLARE
    bad text;
BEGIN
    SELECT string_agg(s.scientific_name, ', ') INTO bad
    FROM tet_sheet s
    WHERE (SELECT count(*) FROM public.species_en e
           WHERE lower(btrim(e.scientific_name)) = lower(btrim(s.scientific_name))) <> 1;
    IF bad IS NOT NULL THEN
        RAISE EXCEPTION 'Tetum load: these sheet species do not match exactly one species_en row: %', bad;
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS public.species_tet_backup_{STAMP} (LIKE public.species_tet);
ALTER TABLE public.species_tet_backup_{STAMP} ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.species_tet_backup_{STAMP} FROM anon, authenticated;
INSERT INTO public.species_tet_backup_{STAMP}
SELECT * FROM public.species_tet
WHERE NOT EXISTS (SELECT 1 FROM public.species_tet_backup_{STAMP});

CREATE TEMP TABLE tet_load ON COMMIT DROP AS
SELECT e.species_id, e.scientific_name AS en_name, s.*
FROM tet_sheet s
JOIN public.species_en e ON lower(btrim(e.scientific_name)) = lower(btrim(s.scientific_name));

UPDATE public.species_tet t
SET scientific_name = l.en_name,
{",\n".join(f"    {c} = l.{c}" for c in TEXT_COLS)}
FROM tet_load l
WHERE t.species_id = l.species_id;

INSERT INTO public.species_tet (species_id, scientific_name, {", ".join(TEXT_COLS)})
SELECT l.species_id, l.en_name, {", ".join("l." + c for c in TEXT_COLS)}
FROM tet_load l
WHERE NOT EXISTS (SELECT 1 FROM public.species_tet t WHERE t.species_id = l.species_id);

CREATE TEMP TABLE tet_orphans ON COMMIT DROP AS
SELECT t.species_id FROM public.species_tet t
WHERE NOT EXISTS (SELECT 1 FROM public.species_en e WHERE e.species_id = t.species_id);

DELETE FROM public.species_tet t USING tet_orphans o WHERE t.species_id = o.species_id;

LOCK TABLE public.changelog IN EXCLUSIVE MODE;
INSERT INTO public.changelog (version, entity_id, entity_type, operation)
SELECT base.v + row_number() OVER (ORDER BY c.op, c.species_id), c.species_id, 'species', c.op
FROM (SELECT species_id, 'UPDATE' AS op FROM tet_load
      UNION ALL
      SELECT species_id, 'DELETE' AS op FROM tet_orphans) c
CROSS JOIN (SELECT coalesce(max(version), 0) AS v FROM public.changelog) base;

DO $$
DECLARE
    missing int; extra int; dup int; loaded int;
BEGIN
    SELECT count(*) INTO missing FROM public.species_en e
    WHERE NOT EXISTS (SELECT 1 FROM public.species_tet t WHERE t.species_id = e.species_id);
    SELECT count(*) INTO extra FROM public.species_tet t
    WHERE NOT EXISTS (SELECT 1 FROM public.species_en e WHERE e.species_id = t.species_id);
    SELECT count(*) - count(DISTINCT species_id) INTO dup FROM public.species_tet;
    SELECT count(*) INTO loaded FROM public.species_tet t JOIN tet_load l USING (species_id)
    WHERE t.common_name = l.common_name AND t.pest = l.pest AND t.leaf_type = l.leaf_type;
    IF missing <> 0 OR extra <> 0 OR dup <> 0 OR loaded <> (SELECT count(*) FROM tet_load) THEN
        RAISE EXCEPTION 'Tetum load check failed: missing=% extra=% duplicate=% loaded=%', missing, extra, dup, loaded;
    END IF;
    RAISE NOTICE 'Tetum load OK: % species updated, % duplicate Tetum rows removed', loaded,
        (SELECT count(*) FROM tet_orphans);
END $$;

COMMIT;

-- After COMMIT, this should list 22 rows with the new Tetum common names:
SELECT t.species_id, t.scientific_name, t.common_name, t.leaf_type, t.fruit_type
FROM public.species_tet t ORDER BY t.species_id;
"""

rollback = f"""-- Rollback for 01-load-tetum-translation-{STAMP}.sql
-- Restores species_tet exactly as it was before the load (including the 5 duplicate
-- rows), and logs an UPDATE for every restored species so installed apps re-sync.
BEGIN;
DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM public.species_tet_backup_{STAMP}) THEN
        RAISE EXCEPTION 'No backup rows in species_tet_backup_{STAMP}; nothing to restore';
    END IF;
END $$;
DELETE FROM public.species_tet;
INSERT INTO public.species_tet SELECT * FROM public.species_tet_backup_{STAMP};
LOCK TABLE public.changelog IN EXCLUSIVE MODE;
INSERT INTO public.changelog (version, entity_id, entity_type, operation)
SELECT base.v + 1, NULL, 'species', 'RESTORE_TETUM_{STAMP}'
FROM (SELECT coalesce(max(version), 0) AS v FROM public.changelog) base;
COMMIT;
"""

(OUT / f"01-load-tetum-translation-{STAMP}.sql").write_text(sql, encoding="utf-8")
(OUT / f"rollback-01-load-tetum-translation-{STAMP}.sql").write_text(rollback, encoding="utf-8")
print("wrote", OUT, "| term changes vs sheet:", len(changed_terms))
for c in changed_terms:
    print("  ", c[0], c[1], ":", c[2], "->", c[3])
