import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const target = fileURLToPath(new URL("../packages/shared/src/database.ts", import.meta.url));
const run = (command, args, options) =>
  execFileSync(command, args, { shell: process.platform === "win32", ...options });

const types = run("supabase", ["gen", "types", "typescript", "--schema", "public"], {
  encoding: "utf8",
  stdio: ["ignore", "pipe", "inherit"],
});

writeFileSync(
  target,
  `// Generated by \`pnpm gen:types\` from services/flask-api/TableSchema.sql. Do not edit by hand.\n\n${types}`,
);
run("oxfmt", [target], { stdio: "inherit" });
