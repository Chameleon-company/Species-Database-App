import { writeFileSync } from "node:fs";
import { text } from "node:stream/consumers";

const target = new URL("../packages/shared/src/database.ts", import.meta.url);

if (process.stdin.isTTY) {
  console.error("Run `pnpm gen:types`. This script reads the generated types from stdin.");
  process.exit(1);
}

const types = await text(process.stdin);

if (!types.includes("export type Database")) {
  console.error(
    "No database types on stdin. Run `pnpm supabase db start` first, then `pnpm gen:types`.",
  );
  process.exit(1);
}

writeFileSync(
  target,
  `// Generated by \`pnpm gen:types\` from the local database, which loads services/flask-api/TableSchema.sql. Do not edit by hand.\n\n${types}`,
);
