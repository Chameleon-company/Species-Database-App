import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";

const pulled = new URL("../apps/api/.drizzle-pull/", import.meta.url);
const target = new URL("../apps/api/src/db/schema.ts", import.meta.url);

const schema = readFileSync(new URL("schema.ts", pulled), "utf8");
mkdirSync(new URL(".", target), { recursive: true });
writeFileSync(
  target,
  `// Generated by \`pnpm gen:types\` from the local database, which loads services/flask-api/TableSchema.sql. Do not edit by hand.\n\n${schema}`,
);
rmSync(pulled, { recursive: true, force: true });
