#!/usr/bin/env bash
# Writes packages/shared/src/database.ts from the local database. Run `pnpm supabase db start` first.
# The file is replaced only when generation succeeds.
set -euo pipefail

target="packages/shared/src/database.ts"
tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT

{
  echo "// Generated by \`pnpm gen:types\` from services/flask-api/TableSchema.sql. Do not edit by hand."
  echo
  supabase gen types typescript --schema public
} >"$tmp"

mv "$tmp" "$target"
oxfmt "$target"
